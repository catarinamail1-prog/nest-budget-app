function interpolate(str, params) {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (m, key) => (key in params ? params[key] : m));
}

// Detecta o idioma do navegador do comprador (navigator.languages, em ordem de preferência)
// e devolve o primeiro que o app suporta — usado para já abrir o quiz no idioma certo,
// sem esperar o comprador ir em Configurações trocar manualmente.
export function detectBrowserLang(fallback = 'en') {
  const supported = Object.keys(DICT);
  const nav = typeof navigator !== 'undefined' ? navigator : null;
  const candidates = (nav && nav.languages && nav.languages.length)
    ? nav.languages
    : (nav && nav.language ? [nav.language] : []);
  for (const loc of candidates) {
    const full = String(loc).toLowerCase();
    // 1) correspondência completa (ex: "pt-BR", "pt-PT") — cobre os dois portugueses e qualquer
    //    outro idioma com variante regional que o dicionário venha a ganhar no futuro.
    const exact = supported.find(s => s.toLowerCase() === full);
    if (exact) return exact;
    const primary = full.split('-')[0];
    const region = full.split('-')[1];
    // 2) português sem correspondência exata: decide pela região quando o navegador informa uma
    //    ("pt-PT" -> Portugal); qualquer outra região de português (ou nenhuma) cai em "pt-BR",
    //    que é o público majoritário do produto.
    if (primary === 'pt') return region === 'pt' ? 'pt-PT' : 'pt-BR';
    // 3) demais idiomas, sem variante regional no dicionário: casa pelo código principal.
    const byPrimary = supported.find(s => s.toLowerCase() === primary);
    if (byPrimary) return byPrimary;
  }
  return fallback;
}

export const I18n = {
  setLang(lang) {
    currentLang = DICT[lang] ? lang : 'en';
  },
  getLang() {
    return currentLang;
  },
  t(key, params) {
    const str = (DICT[currentLang] && DICT[currentLang][key]) || DICT.en[key] || key;
    return interpolate(str, params);
  }
};
